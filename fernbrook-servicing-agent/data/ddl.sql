-- Fernbrook Member Services Agent: Snowflake setup.
-- Run section 1 as ACCOUNTADMIN, sections 2-3 as FERNBROOK_LOADER.
-- Column names are UPPERCASE and unquoted on purpose: Data 360 federation does not
-- support renaming or re-capitalizing Snowflake columns, so freeze this schema first.

-- ===== 1. Warehouse, database, roles, users (ACCOUNTADMIN) =====
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS FERNBROOK_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS FERNBROOK;
CREATE SCHEMA   IF NOT EXISTS FERNBROOK.SERVICE;

-- Loader role: writes data (used by data/load_snowflake.py)
CREATE ROLE IF NOT EXISTS FERNBROOK_LOADER;
GRANT USAGE ON WAREHOUSE FERNBROOK_WH TO ROLE FERNBROOK_LOADER;
GRANT ALL ON DATABASE FERNBROOK TO ROLE FERNBROOK_LOADER;
GRANT ALL ON SCHEMA FERNBROOK.SERVICE TO ROLE FERNBROOK_LOADER;
-- >>> replace with your Snowflake login name <<<
GRANT ROLE FERNBROOK_LOADER TO USER <YOUR_SNOWFLAKE_USER>;

-- Read-only role + user for the Data 360 connection (least privilege)
CREATE ROLE IF NOT EXISTS FERNBROOK_D360_RO;
GRANT USAGE ON WAREHOUSE FERNBROOK_WH TO ROLE FERNBROOK_D360_RO;
GRANT USAGE ON DATABASE FERNBROOK TO ROLE FERNBROOK_D360_RO;
GRANT USAGE ON SCHEMA FERNBROOK.SERVICE TO ROLE FERNBROOK_D360_RO;
GRANT SELECT ON ALL TABLES IN SCHEMA FERNBROOK.SERVICE TO ROLE FERNBROOK_D360_RO;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FERNBROOK.SERVICE TO ROLE FERNBROOK_D360_RO;

-- >>> choose a strong password; do not commit it <<<
CREATE USER IF NOT EXISTS D360_RO_USER
  PASSWORD = '<STRONG_PASSWORD>' DEFAULT_ROLE = FERNBROOK_D360_RO
  DEFAULT_WAREHOUSE = FERNBROOK_WH MUST_CHANGE_PASSWORD = FALSE;
GRANT ROLE FERNBROOK_D360_RO TO USER D360_RO_USER;

-- ===== 2. Tables (FERNBROOK_LOADER) =====
USE ROLE FERNBROOK_LOADER;
USE WAREHOUSE FERNBROOK_WH;
USE SCHEMA FERNBROOK.SERVICE;

CREATE OR REPLACE TABLE PLANS (
  PLAN_ID STRING, PLAN_NAME STRING, TIER STRING, DEDUCTIBLE NUMBER(10,2), OOP_MAX NUMBER(10,2));

CREATE OR REPLACE TABLE MEMBERS (
  MEMBER_ID STRING, NAME STRING, DOB DATE, EMAIL STRING, ZIP STRING, PLAN_ID STRING, STATUS STRING);

CREATE OR REPLACE TABLE ACCUMULATORS (
  MEMBER_ID STRING, PLAN_YEAR NUMBER(4,0), DEDUCTIBLE_MET NUMBER(10,2), OOP_MET NUMBER(10,2), AS_OF TIMESTAMP_NTZ);

CREATE OR REPLACE TABLE CLAIMS (
  CLAIM_ID STRING, MEMBER_ID STRING, SERVICE_DATE DATE, SERVICE_CODE STRING, PROVIDER STRING,
  BILLED NUMBER(10,2), MEMBER_OWES NUMBER(10,2), STATUS STRING, STATUS_REASON STRING, UPDATED_AT TIMESTAMP_NTZ);

CREATE OR REPLACE TABLE PRIOR_AUTHS (
  AUTH_ID STRING, MEMBER_ID STRING, SERVICE_CODE STRING, STATUS STRING,
  SUBMITTED_AT TIMESTAMP_NTZ, DECIDED_AT TIMESTAMP_NTZ);

CREATE OR REPLACE TABLE SERVICE_REQUESTS (
  REQUEST_ID STRING, MEMBER_ID STRING, TYPE STRING, STATUS STRING,
  OPENED_AT TIMESTAMP_NTZ, CLOSED_AT TIMESTAMP_NTZ);

-- CLAIM_ID is an addition to the planned schema: the "3 contacts about the same claim
-- in 7 days" rule needs it. Nullable; blank for non-claim intents.
CREATE OR REPLACE TABLE INTERACTIONS (
  INTERACTION_ID STRING, MEMBER_ID STRING, CHANNEL STRING, INTENT STRING, CLAIM_ID STRING,
  STARTED_AT TIMESTAMP_NTZ, HANDLE_SECS NUMBER(8,0), RESOLVED_FLAG BOOLEAN, CSAT NUMBER(2,0));

CREATE OR REPLACE TABLE CALL_TRANSCRIPTS (
  TRANSCRIPT_ID STRING, INTERACTION_ID STRING, MEMBER_ID STRING, TEXT STRING);

CREATE OR REPLACE TABLE CASE_NOTES (
  NOTE_ID STRING, REQUEST_ID STRING, AUTHOR_ROLE STRING, TEXT STRING, CREATED_AT TIMESTAMP_NTZ);

-- ===== 3. Re-grant (tables were re-created) =====
USE ROLE ACCOUNTADMIN;
GRANT SELECT ON ALL TABLES IN SCHEMA FERNBROOK.SERVICE TO ROLE FERNBROOK_D360_RO;
