-- Story 1: denied for missing prior auth, member has no auth for that code (expect 1 claim, 0 auths)
SELECT c.CLAIM_ID, c.STATUS_REASON,
       (SELECT COUNT(*) FROM PRIOR_AUTHS a WHERE a.MEMBER_ID=c.MEMBER_ID AND a.SERVICE_CODE=c.SERVICE_CODE) AS matching_auths
FROM CLAIMS c WHERE c.MEMBER_ID='M0000001' AND c.STATUS_REASON='PRIOR_AUTH_MISSING' AND c.SERVICE_CODE='73721'
  AND c.PROVIDER LIKE 'Riverbend%';

-- Story 2: 3 contacts in 7 days about the same claim (expect 3)
SELECT MEMBER_ID, CLAIM_ID, COUNT(*) AS contacts FROM INTERACTIONS
WHERE STARTED_AT >= DATEADD(day,-7,'2026-10-01 12:00:00'::timestamp_ntz) AND MEMBER_ID='M0000002'
GROUP BY 1,2 HAVING COUNT(*) >= 3;

-- Story 5: intent skew (top 4 should be roughly 78% of volume)
SELECT INTENT, COUNT(*) n, ROUND(100*COUNT(*)/SUM(COUNT(*)) OVER (),1) pct, ROUND(AVG(HANDLE_SECS)) avg_handle
FROM INTERACTIONS GROUP BY 1 ORDER BY n DESC;

